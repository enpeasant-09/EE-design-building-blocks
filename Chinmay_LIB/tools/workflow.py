#!/usr/bin/env python3
"""workflow.py - living context docs for the Chinmay KiCad library projects.

Each project folder gets docs/workflow.json (the state) and docs/CONTEXT.md (generated from the
state plus a scan of the KiCad files). Update the state at every stage; never hand-edit CONTEXT.md.
A new session (human or AI) reads CONTEXT.md instead of being told the history again.

  python workflow.py status                              all projects, one line each
  python workflow.py stage Chinmay_MEMORY layout --status wip --note "NOR blocks placed"
  python workflow.py log   Chinmay_BUCK "MAX17503 moved to 4x4 TQFN land 90-0409"
  python workflow.py open  Chinmay_XTAL "Verify CL on 48 MHz part"      (add an open item)
  python workflow.py close Chinmay_XTAL 1                               (close open item 1)
  python workflow.py refresh                             rescan KiCad files, rewrite every CONTEXT.md

Repo root = two levels above this file (…/Chinmay_LIB/tools/workflow.py), or --root PATH.
"""
import argparse, datetime, json, pathlib, re, sys

STAGES = [('parts', 'Select parts, check stock'), ('datasheet', 'Datasheet capture'), ('calc', 'Calculations'),
          ('symbols', 'Symbols'), ('schematic', 'Schematic / blocks'), ('erc', 'ERC + render check'),
          ('footprints', 'Footprint review'), ('models3d', '3D models'), ('layout', 'PCB layout in block'),
          ('review', 'Peer review'), ('release', 'Merged to main')]
STATUS = {'done': 'done', 'wip': 'in progress', 'todo': 'not started', 'na': 'not applicable'}
SYM = re.compile(r'\(symbol\s+\(lib_id\s+"([^"]+)"\)')

def today(): return datetime.date.today().isoformat()
def prop(chunk, name):
    m = re.search(r'\(property\s+"%s"\s+"([^"]*)"' % re.escape(name), chunk)
    return m.group(1) if m else ''

def scan_sch(path):
    """Placed symbols of one schematic: list of (ref, value, footprint, mpn)."""
    t = path.read_text(encoding='utf-8', errors='ignore')
    i = t.find('(lib_symbols'); body = t
    if i >= 0:                       # skip the embedded library section
        d = 0
        for j in range(i, len(t)):
            d += t[j] == '('; d -= t[j] == ')'
            if d == 0: body = t[j:]; break
    ms = list(SYM.finditer(body)); out = []
    for k, m in enumerate(ms):
        ch = body[m.start(): ms[k + 1].start() if k + 1 < len(ms) else len(body)]
        ref = prop(ch, 'Reference')
        if ref.startswith('#'): continue
        out.append((ref, prop(ch, 'Value'), prop(ch, 'Footprint'), prop(ch, 'MPN1') or prop(ch, 'MPN')))
    return out

def scan_project(pdir):
    """-> list of dicts: family, name, kind, main, parts, has_layout."""
    items = []
    for lib in sorted(pdir.glob('*.kicad_blocks')):
        for b in sorted(lib.glob('*.kicad_block')):
            sch = b / (b.stem + '.kicad_sch')
            if sch.exists(): items.append(_item(lib.stem, b.stem, 'block', sch, any(b.glob('*.kicad_pcb'))))
    for sch in sorted(pdir.glob('*.kicad_sch')):
        if sch.stem.lower() in (pdir.name.lower(), 'scratch'): continue
        items.append(_item(pdir.name, sch.stem, 'sheet', sch, False))
    return items

def _item(family, name, kind, sch, has_layout):
    parts = scan_sch(sch)
    ics = [p for p in parts if re.match(r'(U|Y|X|Q)\d*\??', p[0])]
    main = ics[0] if ics else (parts[0] if parts else ('', '', '', ''))
    return dict(family=family, name=name, kind=kind, main=main[1], mpn=main[3], fp=main[2].split(':')[-1],
                parts=len(parts), has_layout=has_layout)

def load(pdir):
    f = pdir / 'docs' / 'workflow.json'
    if f.exists(): return json.loads(f.read_text(encoding='utf-8'))
    return dict(purpose='', stages={k: dict(status='todo', note='', date='') for k, _ in STAGES}, log=[], open=[], next='')

def save(pdir, st):
    (pdir / 'docs').mkdir(exist_ok=True)
    (pdir / 'docs' / 'workflow.json').write_text(json.dumps(st, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')

def mm(s): return re.sub(r'["\[\]{}()<>|#;]', ' ', s).strip()

def render(pdir, st):
    items = scan_project(pdir); L = []
    L += [f'# {pdir.name} - project context', '',
          f'> Generated by `Chinmay_LIB/tools/workflow.py` on {today()}. Do not edit by hand: change `docs/workflow.json` through the tool, then `refresh`.', '',
          st.get('purpose', ''), '', '## Where this project stands', '']
    cur = next((k for k, _ in STAGES if st['stages'][k]['status'] in ('wip', 'todo')), None)
    L += [f"**Next step:** {st.get('next') or (dict(STAGES)[cur] if cur else 'nothing pending')}", '', '```mermaid', 'flowchart LR']
    for k, lab in STAGES:
        s = st['stages'][k]; L.append(f'  {k}["{lab}<br/>{STATUS[s["status"]]}"]:::{s["status"]}')
    L.append('  ' + ' --> '.join(k for k, _ in STAGES))
    L += ['  classDef done fill:#d5f0d5,stroke:#2e7d32,color:#111', '  classDef wip fill:#fff3c4,stroke:#b58900,color:#111',
          '  classDef todo fill:#eeeeee,stroke:#888,color:#111', '  classDef na fill:#ffffff,stroke:#bbb,color:#888,stroke-dasharray:3', '```', '',
          '| Stage | Status | Updated | Note |', '|---|---|---|---|']
    for k, lab in STAGES:
        s = st['stages'][k]; L.append(f"| {lab} | {STATUS[s['status']]} | {s['date']} | {s['note']} |")
    L += ['', '## What is in the project', '']
    fams = {}
    for it in items: fams.setdefault(it['family'], []).append(it)
    L += ['```mermaid', 'flowchart LR', f'  P(["{mm(pdir.name)}"])']
    n = 0
    for fi, (fam, its) in enumerate(fams.items()):
        L.append(f'  P --> F{fi}["{mm(fam)}<br/>{len(its)} {its[0]["kind"]}s"]')
        for it in its:
            n += 1; L.append(f'  F{fi} --> B{n}["{mm(it["name"])}<br/>{mm(it["main"])}"]' + (':::lay' if it['has_layout'] else ''))
    L += ['  classDef lay fill:#d5f0d5,stroke:#2e7d32,color:#111', '```', '',
          'Green boxes already carry a PCB layout.', '', '| Family | Block / sheet | Main part | MPN | Package | Parts | Layout |', '|---|---|---|---|---|---|---|']
    for it in items:
        L.append(f"| {it['family']} | {it['name']} | {it['main']} | {it['mpn']} | {it['fp']} | {it['parts']} | {'yes' if it['has_layout'] else 'no'} |")
    L += ['', '## Open items', '']
    op = [o for o in st['open'] if not o.get('closed')]
    L += [f"{i + 1}. {o['text']} _(opened {o['date']})_" for i, o in enumerate(op)] or ['None.']
    L += ['', '## Decisions and changes (newest first)', '']
    L += [f"- **{e['date']}** [{e['stage']}] {e['text']}" for e in reversed(st['log'])] or ['None yet.']
    (pdir / 'docs').mkdir(exist_ok=True)
    (pdir / 'docs' / 'CONTEXT.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    return items

def projects(root): return sorted(p for p in root.iterdir() if p.is_dir() and p.name.startswith('Chinmay_') and p.name != 'Chinmay_LIB')

def render_root(root):
    L = ['# EE design building blocks - context index', '',
         f'> Generated by `Chinmay_LIB/tools/workflow.py` on {today()}. Read this first, then the CONTEXT.md of the project you are working on.', '',
         '## How work flows', '', '```mermaid', 'flowchart TD',
         '  A[Start a session] --> B[Read CONTEXT.md of the project]', '  B --> C[Do one stage of work]',
         '  C --> D["workflow.py stage / log / open"]', '  D --> E[CONTEXT.md regenerated]', '  E --> F[Commit docs with the change]', '  F --> A', '```', '',
         '## Projects', '', '| Project | Blocks / sheets | Done | Current stage | Next step |', '|---|---|---|---|---|']
    for p in projects(root):
        st = load(p); items = render(p, st)
        done = sum(1 for k, _ in STAGES if st['stages'][k]['status'] in ('done', 'na'))
        cur = next((dict(STAGES)[k] for k, _ in STAGES if st['stages'][k]['status'] in ('wip', 'todo')), 'complete')
        L.append(f"| [{p.name}]({p.name}/docs/CONTEXT.md) | {len(items)} | {done}/{len(STAGES)} | {cur} | {st.get('next', '')} |")
    L += ['', '## Shared library', '', '`Chinmay_LIB` holds the footprints, STEP models, the generator scripts (`tools/`) and the method document.',
          'Graphify indexes only the Python in `tools/`; KiCad files are covered by these context docs instead.', '']
    (root / 'CONTEXT.md').write_text('\n'.join(L), encoding='utf-8')

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--root', default=str(pathlib.Path(__file__).resolve().parents[2]))
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('status'); sub.add_parser('refresh')
    s = sub.add_parser('stage'); s.add_argument('project'); s.add_argument('stage', choices=[k for k, _ in STAGES])
    s.add_argument('--status', choices=list(STATUS), required=True); s.add_argument('--note', default=''); s.add_argument('--next', default=None)
    for name in ('log', 'open'):
        s = sub.add_parser(name); s.add_argument('project'); s.add_argument('text'); s.add_argument('--stage', default='general')
    s = sub.add_parser('close'); s.add_argument('project'); s.add_argument('number', type=int)
    a = ap.parse_args(); root = pathlib.Path(a.root)
    if a.cmd == 'status':
        for p in projects(root):
            st = load(p); print(f"{p.name:18}", ' '.join(f"{k}:{st['stages'][k]['status']}" for k, _ in STAGES))
        return
    if a.cmd != 'refresh':
        p = root / a.project
        if not p.is_dir(): sys.exit(f'no such project folder: {p}')
        st = load(p)
        if a.cmd == 'stage':
            st['stages'][a.stage] = dict(status=a.status, note=a.note, date=today())
            if a.next is not None: st['next'] = a.next
            st['log'].append(dict(date=today(), stage=a.stage, text=f'{STATUS[a.status]}' + (f': {a.note}' if a.note else '')))
        elif a.cmd == 'log': st['log'].append(dict(date=today(), stage=a.stage, text=a.text))
        elif a.cmd == 'open': st['open'].append(dict(date=today(), text=a.text))
        elif a.cmd == 'close':
            op = [o for o in st['open'] if not o.get('closed')]
            if not 1 <= a.number <= len(op): sys.exit('no such open item')
            op[a.number - 1]['closed'] = today(); st['log'].append(dict(date=today(), stage='general', text='closed: ' + op[a.number - 1]['text']))
        save(p, st)
    render_root(root); print('context docs refreshed')

if __name__ == '__main__': main()
